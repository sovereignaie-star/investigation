/** أدوات السند المشتركة — كلمات المحتوى (P5-013). */
const STOPWORDS = new Set([
  "في",
  "من",
  "إلى",
  "على",
  "عن",
  "عند",
  "منذ",
  "مع",
  "بين",
  "هذا",
  "هذه",
  "التي",
  "الذي",
  "كل",
  "لا",
  "ما",
  "إن",
  "أن",
  "أو",
  "هو",
  "هي",
  "فيه",
  "the",
  "a",
  "an",
  "in",
  "on",
  "at",
  "of",
  "for",
  "since",
  "is",
  "are",
  "by",
  "and",
  "to",
]);

/**
 * كلمات المحتوى: رموز عربية/لاتينية (تشمل النقاط الداخلية للنطاقات والعناوين).
 * التطبيع: تُحذف علامات التشكيل العربية (الشددة والتنوين تفصلان الكلمة
 * وهمياً) والتطويل قبل التقسيم، ولا يبدأ الرمز ولا ينتهي بعلامة (فالنقطة
 * الطرفية من «2026.» جزء من الجملة لا من الرمز).
 */
export function contentTokens(text: string): Set<string> {
  const cleaned = text.replace(/\p{M}/gu, "").replace(/\u0640/gu, "");
  const tokens = cleaned.match(/[\p{L}\p{N}]([\p{L}\p{N}._'’-]*[\p{L}\p{N}])?/gu) ?? [];
  return new Set(tokens.map((t) => t.toLowerCase()).filter((t) => t.length > 1 && !STOPWORDS.has(t)));
}
