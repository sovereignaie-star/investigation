// Regenerates the data modules of @ir/core from the vendored registries in packages/core/data (P1-005):
//   data/iban.dat                  SWIFT IBAN registry (via python-stdnum)      -> src/validators/iban-registry.ts
//   data/public_suffix_list.dat    Mozilla Public Suffix List                   -> src/psl/rules.ts
// Run: pnpm --filter @ir/core run gen:data
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { domainToASCII } from "node:url";

const root = path.resolve(import.meta.dirname, "..");
const read = (f) => readFileSync(path.join(root, f), "utf8");

// IBAN: country code -> BBAN pattern (n digits, a upper-case letters, c alphanumerics, e space; "!" = fixed length).
const cls = { n: "[0-9]", a: "[A-Z]", c: "[0-9A-Z]", e: " " };
const iban = {};
for (const line of read("data/iban.dat").split("\n")) {
  const m = /^([A-Z]{2}) country="[^"]*" bban="([^"]+)"/.exec(line);
  if (!m) continue;
  let re = "";
  let len = 4;
  for (const [, n, fixed, t] of m[2].matchAll(/(\d+)(!?)([nace])/g)) {
    re += `${cls[t]}{${fixed ? n : `1,${n}`}}`;
    len += Number(n);
  }
  iban[m[1]] = [len, re];
}
const ibanSrc = `// GENERATED by scripts/gen-data.mjs from data/iban.dat (SWIFT IBAN registry). Do not edit.
/** Country code -> [total IBAN length, BBAN regular expression source]. */
export const IBAN_REGISTRY: Readonly<Record<string, readonly [number, string]>> = ${JSON.stringify(iban, null, 1)};
`;
writeFileSync(path.join(root, "src/validators/iban-registry.ts"), ibanSrc);

// PSL: rules converted to ASCII (punycode) labels; wildcard and exception rules are kept as separate sets.
const rules = [];
const wild = [];
const exc = [];
for (const raw of read("data/public_suffix_list.dat").split("\n")) {
  const line = raw.trim().split(/\s/)[0];
  if (!line || line.startsWith("//")) continue;
  const kind = line.startsWith("!") ? exc : line.startsWith("*.") ? wild : rules;
  const body = line.replace(/^!|^\*\./, "");
  const ascii = domainToASCII(body);
  if (!ascii) throw new Error(`PSL rule not convertible: ${line}`);
  kind.push(ascii);
}
const pslSrc = `// GENERATED by scripts/gen-data.mjs from data/public_suffix_list.dat (https://publicsuffix.org). Do not edit.
export const PSL_RULES = ${JSON.stringify(rules.join("\n"))};
export const PSL_WILDCARDS = ${JSON.stringify(wild.join("\n"))};
export const PSL_EXCEPTIONS = ${JSON.stringify(exc.join("\n"))};
`;
writeFileSync(path.join(root, "src/psl/rules.ts"), pslSrc);
console.log(`iban: ${Object.keys(iban).length} countries; psl: ${rules.length} rules, ${wild.length} wildcards, ${exc.length} exceptions`);
